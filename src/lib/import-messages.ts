/**
 * Казахский вариант сообщений импорта прайса. Разбор файла (catalog-file.ts) отдаёт русские тексты, на них опираются тесты,
 * поэтому перевод делается здесь по шаблонам и применяется в маршруте /api/import по языку кабинета.
 * Неизвестное сообщение остаётся как есть (по-русски): лучше понятное, чем потерянное.
 */
const RULES: [RegExp, (m: RegExpMatchArray) => string][] = [
  [/^В файле больше (\d+) строк\. Разбейте его на части\.$/, (m) => `Файлда ${m[1]} жолдан көп. Оны бөліктерге бөліңіз.`],
  [/^В файле (\d+) товаров, за раз можно не больше (\d+)\. Разбейте его на части\.$/, (m) => `Файлда ${m[1]} тауар бар, бір реттен ${m[2]}-ден көп болмайды. Оны бөліктерге бөліңіз.`],
  [/^Не удалось открыть файл: (.+)\. Пересохраните прайс в Excel как \.xlsx\.$/, (m) => `Файлды ашу мүмкін болмады: ${m[1]}. Прайсты Excel-де .xlsx ретінде қайта сақтаңыз.`],
  [/^Не получилось открыть \.xlsx\. Пересохраните файл в Excel и загрузите ещё раз\.$/, () => "Файлды (.xlsx) ашу мүмкін болмады. Оны Excel-де қайта сақтап, қайта жүктеңіз."],
  [/^В файле нет листа с данными\.$/, () => "Файлда деректері бар парақ жоқ."],
  [/^Файл пустой\.$/, () => "Файл бос."],
  [/^Файл больше 4 МБ\. Разбейте прайс на части\.$/, () => "Файл 4 МБ-тан үлкен. Прайсты бөліктерге бөліңіз."],
  [/^Не нашли колонки с названием и ценой\..*$/, () => "Атауы мен бағасы бар бағандар табылмады. Бірінші жолда тақырыптар болуы керек, мысалы: «Название» және «Цена» (немесе name, price_kzt). Үлгіні жүктеңіз."],
  [/^В файле только заголовки, товаров нет\.$/, () => "Файлда тек тақырыптар бар, тауар жоқ."],
  [/^(артикул|категория|описание|описание на казахском): не длиннее (\d+) символов$/, (m) => {
    const label = { "артикул": "артикул", "категория": "санат", "описание": "сипаттама", "описание на казахском": "қазақша сипаттама" }[m[1]] ?? m[1];
    return `${label}: ${m[2]} таңбадан ұзын емес болуы керек`;
  }],
  [/^нет названия$/, () => "атауы жоқ"],
  [/^название длиннее (\d+) символов$/, (m) => `атауы ${m[1]} таңбадан ұзын`],
  [/^нет цены$/, () => "бағасы жоқ"],
  [/^цена — не число$/, () => "баға — сан емес"],
  [/^цена отрицательная$/, () => "баға теріс"],
  [/^слишком большая цена$/, () => "баға тым үлкен"],
  [/^количество — не число$/, () => "саны — сан емес"],
  [/^количество от 0 до 1 000 000$/, () => "саны 0-ден 1 000 000-ға дейін болуы керек"],
  [/^артикул «(.*)» повторяется, взята строка (\d+)$/, (m) => `«${m[1]}» артикулі қайталанады, ${m[2]}-жол алынды`],
  [/^лимит товаров вашего тарифа$/, () => "тарифтегі тауар шегі"],
  [/^база не приняла значения строки$/, () => "база жол мәндерін қабылдамады"],
];

function translateOne(text: string): string {
  for (const [pattern, build] of RULES) {
    const match = text.match(pattern);
    if (match) return build(match);
  }
  return text;
}

/** Переводит сообщение отчёта или ошибку файла; строки отчёта могут содержать несколько причин через «; ». */
export function importMessageKz(text: string): string {
  const whole = translateOne(text);
  if (whole !== text) return whole;
  return text.split("; ").map(translateOne).join("; ");
}
