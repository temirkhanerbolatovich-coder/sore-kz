import { describe, expect, it } from "vitest";
import { plural } from "@/lib/plural";

describe("plural", () => {
  it("склоняет по русским правилам", () => {
    const f = (n: number) => plural(n, "товар", "товара", "товаров");
    expect([0, 1, 2, 4, 5, 11, 12, 14, 21, 22, 25, 101, 111].map(f)).toEqual([
      "товаров", "товар", "товара", "товара", "товаров", "товаров", "товаров", "товаров", "товар", "товара", "товаров", "товар", "товаров",
    ]);
  });
});
